BOOKS = ["book-navy", "book-teal", "book-green", "book-slate", "book-plum"]
def book_row(x0, x1, base, lo, hi, gap_chance=0.12):
    x = x0
    while x < x1 - 1:
        w = random.choice([2, 2, 3, 3, 4])
        if x + w > x1: break
        if random.random() < gap_chance:
            x += random.choice([2, 3]); continue
        paint = f'{random.choice(BOOKS)}.{random.choice(["shade", "base", "lit"])}'
        emit(f'    rect x={x} y="=({base}) - @self.height" width={w} height="{lo}..{hi}" paint="{paint}"')
        x += w
def stack(x, base, count, wmin, wmax):
    y = base
